// Real-time Gmail inbox socket validator: checks directly with Google SMTP server
export function verifyGmailInboxLive(email: string): Promise<{ exists: boolean; code?: string; error?: string }> {
  const cleanEmail = email.trim().toLowerCase();
  if (!cleanEmail.endsWith('@gmail.com') && !cleanEmail.endsWith('@googlemail.com')) {
    return Promise.resolve({ exists: true }); // Non-gmail domains handled via standard DNS MX
  }

  return new Promise((resolve) => {
    const socket = net.createConnection(25, 'gmail-smtp-in.l.google.com');
    let step = 0;
    socket.setEncoding('utf8');
    socket.setTimeout(4500);

    socket.on('data', (chunk) => {
      const data = chunk.toString('utf8');
      if (step === 0 && data.startsWith('220')) {
        step = 1;
        socket.write('HELO mail.leadhunterpro.com\r\n');
      } else if (step === 1 && data.startsWith('250')) {
        step = 2;
        socket.write('MAIL FROM:<verify@leadhunterpro.com>\r\n');
      } else if (step === 2 && data.startsWith('250')) {
        step = 3;
        socket.write(`RCPT TO:<${cleanEmail}>\r\n`);
      } else if (step === 3) {
        const ok = data.startsWith('250');
        socket.write('QUIT\r\n');
        socket.end();
        resolve({ exists: ok, code: data.slice(0, 3) });
      }
    });

    socket.on('timeout', () => {
      socket.destroy();
      resolve({ exists: false, error: 'Google SMTP timeout' });
    });

    socket.on('error', (err) => {
      resolve({ exists: false, error: err.message });
    });
  });
}

